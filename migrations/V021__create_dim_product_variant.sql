CREATE TABLE IF NOT EXISTS
    {{ DB_NAME }}.SQL_PRACTICE.DIM_PRODUCT_VARIANT (
    VARIANT_SK NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    VARIANT_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER,
    PRODUCT_SK NUMBER,
    INVENTORY_ITEM_ID NUMBER,
    SKU VARCHAR,
    TITLE VARCHAR,
    PRICE FLOAT,
    COMPARE_AT_PRICE VARCHAR,
    OPTION1 VARCHAR,
    OPTION2 VARCHAR,
    OPTION3 VARCHAR,
    BARCODE VARCHAR,
    TRACKED BOOLEAN,
    AVAILABLE_FOR_SALE BOOLEAN,
    REQUIRES_SHIPPING BOOLEAN,
    INVENTORY_POLICY VARCHAR,
    CREATED_AT TIMESTAMP_TZ,
    UPDATED_AT TIMESTAMP_TZ,
    LOAD_DATE TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

MERGE INTO {{ DB_NAME }}.SQL_PRACTICE.DIM_PRODUCT_VARIANT T
USING (
    SELECT
        V.ID AS VARIANT_ID,
        V.PRODUCT_ID,
        P.PRODUCT_SK,
        V.INVENTORY_ITEM_ID,
        V.SKU,
        V.TITLE,
        V.PRICE,
        V.COMPARE_AT_PRICE,
        V.OPTION1,
        V.OPTION2,
        V.OPTION3,
        V.BARCODE,
        V.TRACKED,
        V.AVAILABLE_FOR_SALE,
        V.REQUIRES_SHIPPING,
        V.INVENTORY_POLICY,
        V.CREATED_AT,
        V.UPDATED_AT
    FROM {{ DB_NAME }}.SQL_PRACTICE.STG_PRODUCT_VARIANTS V
    LEFT JOIN {{ DB_NAME }}.SQL_PRACTICE.DIM_PRODUCT P
        ON V.PRODUCT_ID = P.PRODUCT_ID
       AND P.IS_CURRENT = TRUE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY V.ID
        ORDER BY V.UPDATED_AT DESC NULLS LAST
    ) = 1
) S
ON T.VARIANT_ID = S.VARIANT_ID

WHEN MATCHED THEN UPDATE SET
    T.PRODUCT_ID = S.PRODUCT_ID,
    T.PRODUCT_SK = S.PRODUCT_SK,
    T.INVENTORY_ITEM_ID = S.INVENTORY_ITEM_ID,
    T.SKU = S.SKU,
    T.TITLE = S.TITLE,
    T.PRICE = S.PRICE,
    T.COMPARE_AT_PRICE = S.COMPARE_AT_PRICE,
    T.OPTION1 = S.OPTION1,
    T.OPTION2 = S.OPTION2,
    T.OPTION3 = S.OPTION3,
    T.BARCODE = S.BARCODE,
    T.TRACKED = S.TRACKED,
    T.AVAILABLE_FOR_SALE = S.AVAILABLE_FOR_SALE,
    T.REQUIRES_SHIPPING = S.REQUIRES_SHIPPING,
    T.INVENTORY_POLICY = S.INVENTORY_POLICY,
    T.CREATED_AT = S.CREATED_AT,
    T.UPDATED_AT = S.UPDATED_AT,
    T.LOAD_DATE = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    VARIANT_ID,
    PRODUCT_ID,
    PRODUCT_SK,
    INVENTORY_ITEM_ID,
    SKU,
    TITLE,
    PRICE,
    COMPARE_AT_PRICE,
    OPTION1,
    OPTION2,
    OPTION3,
    BARCODE,
    TRACKED,
    AVAILABLE_FOR_SALE,
    REQUIRES_SHIPPING,
    INVENTORY_POLICY,
    CREATED_AT,
    UPDATED_AT
)
VALUES (
    S.VARIANT_ID,
    S.PRODUCT_ID,
    S.PRODUCT_SK,
    S.INVENTORY_ITEM_ID,
    S.SKU,
    S.TITLE,
    S.PRICE,
    S.COMPARE_AT_PRICE,
    S.OPTION1,
    S.OPTION2,
    S.OPTION3,
    S.BARCODE,
    S.TRACKED,
    S.AVAILABLE_FOR_SALE,
    S.REQUIRES_SHIPPING,
    S.INVENTORY_POLICY,
    S.CREATED_AT,
    S.UPDATED_AT
);
