CREATE OR REPLACE VIEW {{ DB_NAME }}.SQL_PRACTICE.STG_DRAFT_ORDERS AS
WITH DRAFT AS (
    SELECT
        *,
        TRY_PARSE_JSON(
            REPLACE(
                REPLACE(
                    REPLACE(
                        REPLACE(PAYMENT_TERMS, '''', '"'),
                        'None', 'null'
                    ),
                    'True', 'true'
                ),
                'False', 'false'
            )
        ) AS PAYMENT_TERMS_JSON
    FROM {{ DB_NAME }}.SQL_PRACTICE.SHOPIFY_DRAFT_ORDERS
)
SELECT
    ID,
    ORDER_ID,
    NAME,
    NOTE,
    TAGS,
    CUSTOMER:id::NUMBER AS CUSTOMER_ID,
    CUSTOMER:email::STRING AS CUSTOMER_EMAIL,
    CUSTOMER:first_name::STRING AS CUSTOMER_FIRST_NAME,
    CUSTOMER:last_name::STRING AS CUSTOMER_LAST_NAME,
    EMAIL,
    STATUS,
    CURRENCY,
    TOTAL_PRICE,
    SUBTOTAL_PRICE,
    TOTAL_TAX,
    TAX_EXEMPT,
    CREATED_AT,
    UPDATED_AT,
    COMPLETED_AT,
    INVOICE_SENT_AT,
    PO_NUMBER,
    INVOICE_URL,
    PAYMENT_TERMS_JSON:id::NUMBER AS PAYMENT_TERMS_ID,
    PAYMENT_TERMS_JSON:payment_terms_name::STRING AS PAYMENT_TERMS_NAME,
    PAYMENT_TERMS_JSON:payment_terms_type::STRING AS PAYMENT_TERMS_TYPE,
    PAYMENT_TERMS_JSON:can_pay_early::BOOLEAN AS CAN_PAY_EARLY,
    BILLING_ADDRESS:city::STRING AS BILLING_CITY,
    BILLING_ADDRESS:province::STRING AS BILLING_STATE,
    BILLING_ADDRESS:country::STRING AS BILLING_COUNTRY,
    BILLING_ADDRESS:zip::STRING AS BILLING_ZIP,
    SHIPPING_ADDRESS:city::STRING AS SHIPPING_CITY,
    SHIPPING_ADDRESS:province::STRING AS SHIPPING_STATE,
    SHIPPING_ADDRESS:country::STRING AS SHIPPING_COUNTRY,
    SHIPPING_ADDRESS:zip::STRING AS SHIPPING_ZIP,
    SHOP_URL,
    _AIRBYTE_EXTRACTED_AT
FROM DRAFT;
