
CREATE OR REPLACE VIEW {{ DB_NAME }}.SQL_PRACTICE.VW_SALES_ANALYTICS AS
SELECT
    F.ORDER_ID,
    F.LINE_ITEM_ID,
    F.PRODUCT_SK,
    P.PRODUCT_ID,
    P.TITLE AS PRODUCT_NAME,
    F.DATE_SK,
    D.FULL_DATE AS ORDER_DATE,
    D.DAY_NAME,
    D.MONTH_NAME,
    D.MONTH_NUMBER,
    D.QUARTER_NUMBER,
    D.YEAR_NUMBER,
    F.QUANTITY,
    F.UNIT_PRICE,
    F.GROSS_AMOUNT,
    F.TOTAL_DISCOUNT,
    F.NET_AMOUNT,
    F.ORDER_CREATED_AT
FROM {{ DB_NAME }}.SQL_PRACTICE.FACT_ORDER_ITEMS F
LEFT JOIN {{ DB_NAME }}.SQL_PRACTICE.DIM_PRODUCT P
    ON F.PRODUCT_SK = P.PRODUCT_SK
LEFT JOIN {{ DB_NAME }}.SQL_PRACTICE.DIM_DATE D
    ON F.DATE_SK = D.DATE_SK;
