CREATE OR REPLACE VIEW SQL_PRACTICE.STG_CUSTOMERS AS
SELECT
    ID,
    FIRST_NAME,
    LAST_NAME,
    EMAIL,
    PHONE,
    CREATED_AT,
    UPDATED_AT,
    STATE,
    CURRENCY,
    SHOP_URL,
    TOTAL_SPENT,
    ORDERS_COUNT,
    LAST_ORDER_ID,
    LAST_ORDER_NAME,
    TAX_EXEMPT,
    VERIFIED_EMAIL,
    ACCEPTS_MARKETING,
    TAGS,
    NOTE,
    DEFAULT_ADDRESS,
    DEFAULT_ADDRESS:city::STRING AS CITY,
    DEFAULT_ADDRESS:province::STRING AS DEFAULT_STATE,
    DEFAULT_ADDRESS:country::STRING AS COUNTRY,
    DEFAULT_ADDRESS:zip::STRING AS ZIP,
    _AIRBYTE_EXTRACTED_AT
FROM SQL_PRACTICE.SHOPIFY_CUSTOMERS;
