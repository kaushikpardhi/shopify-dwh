CREATE OR REPLACE VIEW {{ DB_NAME }}.SQL_PRACTICE.STG_INVENTORY_LEVELS AS
SELECT
    I.ID,
    I.INVENTORY_ITEM_ID,
    I.LOCATION_ID,
    I.AVAILABLE,
    I.QUANTITIES AS QUANTITY,
    MAX(CASE
        WHEN F.VALUE:name::STRING = 'available'
        THEN F.VALUE:quantity::NUMBER
    END) AS AVAILABLE_QTY,
    MAX(CASE
        WHEN F.VALUE:name::STRING = 'on_hand'
        THEN F.VALUE:quantity::NUMBER
    END) AS ON_HAND_QTY,
    MAX(CASE
        WHEN F.VALUE:name::STRING = 'committed'
        THEN F.VALUE:quantity::NUMBER
    END) AS COMMITTED_QTY,
    MAX(CASE
        WHEN F.VALUE:name::STRING = 'incoming'
        THEN F.VALUE:quantity::NUMBER
    END) AS INCOMING_QTY,
    MAX(CASE
        WHEN F.VALUE:name::STRING = 'reserved'
        THEN F.VALUE:quantity::NUMBER
    END) AS RESERVED_QTY,
    I.CREATED_AT,
    I.UPDATED_AT,
    I.SHOP_URL,
    I.CAN_DEACTIVATE,
    I.DEACTIVATION_ALERT,
    I.ADMIN_GRAPHQL_API_ID,
    I._AIRBYTE_EXTRACTED_AT
FROM {{ DB_NAME }}.SQL_PRACTICE.SHOPIFY_INVENTORY_LEVELS I,
LATERAL FLATTEN(INPUT => I.QUANTITIES) F
GROUP BY
    I.ID,
    I.INVENTORY_ITEM_ID,
    I.LOCATION_ID,
    I.AVAILABLE,
    I.CREATED_AT,
    I.UPDATED_AT,
    I.SHOP_URL,
    I.CAN_DEACTIVATE,
    I.DEACTIVATION_ALERT,
    I.ADMIN_GRAPHQL_API_ID,
    I._AIRBYTE_EXTRACTED_AT,
    I.QUANTITIES;
