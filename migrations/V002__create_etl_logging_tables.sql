CREATE TABLE IF NOT EXISTS &{DB_NAME}.SQL_PRACTICE.ETL_AUDIT_LOG
(
    AUDIT_ID         NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    RUN_ID           VARCHAR,
    PIPELINE_NAME    VARCHAR,
    STEP_NAME        VARCHAR,
    STATUS           VARCHAR,
    ROWS_INSERTED    NUMBER DEFAULT 0,
    ROWS_UPDATED     NUMBER DEFAULT 0,
    START_TIME       TIMESTAMP_TZ,
    END_TIME         TIMESTAMP_TZ,
    ERROR_MESSAGE    VARCHAR,
    CREATED_AT       TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS &{DB_NAME}.SQL_PRACTICE.ETL_ERROR_LOG
(
    ERROR_ID       NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    RUN_ID         VARCHAR,
    PIPELINE_NAME  VARCHAR,
    STEP_NAME      VARCHAR,
    ERROR_CODE     VARCHAR,
    ERROR_MESSAGE  VARCHAR,
    QUERY_ID       VARCHAR,
    ERROR_TIME     TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
